#!/usr/bin/env bun
// regen-compare-index.mjs — regenerate compare/index.html from the moments
// ledger (moments/index.jsonl) + the pinned compare fixtures list.
//
// Producer → surface doctrine (agentic-moment AGENTS.md #1): the audit engine
// harvests; the site publishes. The index is DERIVED, never hand-edited: a
// moment added to the ledger shows up on the lab automatically. Pinned
// compare fixtures stay first (they are real trio runs); moments follow.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const siteDir = dirname(fileURLToPath(import.meta.url));
const compareDir = join(siteDir, "compare");
const auditMoments = join(siteDir, "..", "audit", "moments");
const indexJsonl = join(auditMoments, "index.jsonl");

const ESC = { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" };
const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ESC[c]);

// --- pinned compare fixtures (real trio runs) -------------------------------
const FIXTURE_LINKS = [
  ["android-mcp-compare.html", "android-mcp-compare — us-all vs martingeidobler vs dockndevai"],
  ["compare-engine-vendor-vs-canonical.html", "compare-engine-vendor-vs-canonical — old-site-vendor vs trio-canonical"],
  ["log-helper-datadog-vs-oss.html", "log-helper-datadog-vs-oss — datadog-agents vs otel-collector vs vector vs grafana-loki vs signoz"],
  ["typo-audit.html", "typo-audit — mobile near-miss signatures by input mechanism"],
  ["model-catalog-openrouter-vs-rhodochrosite.html", "model-catalog — openrouter dead-lane to rhodochrosite 505"],
];

// Existence-guard every pinned fixture so a dangling href surfaces loudly.
const present = new Set(
  readdirSync(compareDir).filter((f) => f.endsWith(".html") && f !== "index.html" && f !== "compare.html"),
);
const fixtureRows = FIXTURE_LINKS.filter(([href]) => present.has(href))
  .map(([href, label]) => `    <li><a href="${href}">${esc(label)}</a></li>`)
  .join("\n");

// --- moments ledger ----------------------------------------------------------
function buildMomentsRows() {
  try {
    const raw = readFileSync(indexJsonl, "utf8");
    const rows = [];
    for (const line of raw.split("\n")) {
      const t = line.trim();
      if (!t) continue;
      try {
        const m = JSON.parse(t);
        if (!m.file || !m.title) continue;
        const href = m.file.startsWith("../")
          ? m.file // retrospective etc. — relative already
          : `../moments/${m.file}`;
        const tags = Array.isArray(m.tags) && m.tags.length
          ? ` <span style="color:var(--faint)">[${m.tags.map(esc).join(" ")}]</span>`
          : "";
        rows.push(`    <li><a href="${href}">${esc(m.title)}</a>${tags}</li>`);
      } catch {
        /* malformed line — surfaced by the moments index validation tests */
      }
    }
    return rows.join("\n");
  } catch {
    return `    <li style="color:var(--dim)">moments ledger unavailable (${indexJsonl})</li>`;
  }
}

const momentRows = buildMomentsRows();

const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>The Agentic Moment — Compare Lab</title>
<style>
:root{ --ink:#e8e4d8; --dim:#9a9488; --faint:#3a382f; --accent:#c9a227; --bg:#0d0c0a; --card:#141310; }
*{margin:0;padding:0;box-sizing:border-box}
body{ background:var(--bg); color:var(--ink); font:15px/1.55 ui-monospace,monospace; padding:2rem; max-width:1100px; margin:0 auto }
h1{ font-size:1.3rem; letter-spacing:.08em; color:var(--accent); margin-bottom:.3rem }
h2{ font-size:1rem; letter-spacing:.06em; color:var(--dim); margin-top:1.8rem; margin-bottom:.6rem; border-bottom:1px solid var(--faint); padding-bottom:.3rem }
.sub{ color:var(--dim); margin-bottom:1.6rem; font-size:.85rem }
li{ margin:.5rem 0 }
a{ color:var(--accent) }
.meta{ color:var(--faint); font-size:.75rem; margin-top:2rem; border-top:1px solid var(--faint); padding-top:.6rem }
</style>
</head>
<body>
<h1>COMPARE LAB</h1>
<p class="sub">pinned real trio-compare fixtures · <a href="compare.html">interactive lab →</a> · regenerated from the moments ledger</p>
<h2>pinned fixture runs</h2>
<ul>
${fixtureRows}
</ul>
<h2>agentic moments (ledger)</h2>
<ul>
${momentRows}
</ul>
<p class="meta">generated by regen-compare-index.mjs · ${new Date().toISOString()}</p>
</body>
</html>
`;

writeFileSync(join(compareDir, "index.html"), html);
console.log(`compare/index.html regenerated: ${fixtureRows.split("\n").filter(Boolean).length} fixtures, ${momentRows.split("\n").filter(Boolean).length} moments`);